-- ==============================================================================
-- Script de Inicialización de Base de Datos para Agente de Soporte RAG
-- Motor: Oracle Database 26ai (Base DB Service o Autonomous Database)
-- Funcionalidad: Oracle AI Vector Search nativo
-- ==============================================================================

-- 1. Tabla de Base de Conocimiento con Vector Search Nativo
CREATE TABLE IF NOT EXISTS knowledge_base (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL,
    category VARCHAR2(100),
    content CLOB NOT NULL,
    metadata JSON,
    embedding VECTOR(768, FLOAT32), -- Dimensión 768 para modelos de alta precisión (multilingual-e5-base)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Índice Vectorial HNSW (In-Memory Neighbor Graph) para búsqueda a escala
-- Requiere que 'vector_memory_size' > 0 esté configurado en el servidor (Enterprise Edition / SPFILE).
-- En Oracle SE2 o configuraciones estándar, Oracle 26ai utiliza Exact Vector Search (SIMD nativo) automáticamente.
CREATE VECTOR INDEX IF NOT EXISTS idx_knowledge_embedding 
ON knowledge_base (embedding)
ORGANIZATION INMEMORY NEIGHBOR GRAPH
DISTANCE COSINE;

-- 3. Tabla de Auditoría y Registro de Tickets Atendidos por el Agente
CREATE TABLE IF NOT EXISTS agent_tickets_log (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_external_id VARCHAR2(100),
    user_query CLOB NOT NULL,
    retrieved_context CLOB,
    agent_response CLOB,
    confidence_score NUMBER(5, 4),
    status VARCHAR2(50) DEFAULT 'auto_resolved', -- auto_resolved, escalated, draft
    execution_time_ms NUMBER(10),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
